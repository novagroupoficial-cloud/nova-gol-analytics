  function detectar() {
    try { const g = localStorage.getItem("gep_idioma"); if (T[g]) return g; } catch (e) { /* sin almacenamiento */ }
    const n = (navigator.language || "es").slice(0, 2).toLowerCase();
    return T[n] ? n : "es";
  }

  let actual = detectar();

  window.I18N = {
    get idioma() { return actual; },
    get locale() { return T[actual].locale; },
    t(clave, vars) {
      let s = T[actual][clave] ?? T.es[clave] ?? clave;
      if (vars) for (const k in vars) s = s.split(`{${k}}`).join(vars[k]);
      return s;
    },
    cambiar(id) {
      if (!T[id]) return;
      actual = id;
      try { localStorage.setItem("gep_idioma", id); } catch (e) { /* sin almacenamiento */ }
      document.documentElement.lang = id;
      this.aplicar();
      document.dispatchEvent(new CustomEvent("idioma"));
    },
    aplicar(raiz = document) {
      raiz.querySelectorAll("[data-t]").forEach((el) => { el.textContent = this.t(el.dataset.t); });
      raiz.querySelectorAll("[data-t-ph]").forEach((el) => { el.placeholder = this.t(el.dataset.tPh); });
      raiz.querySelectorAll("[data-t-aria]").forEach((el) => { el.setAttribute("aria-label", this.t(el.dataset.tAria)); });
      document.querySelectorAll(".idiomas button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.idioma === actual)));
    },
  };
  document.documentElement.lang = actual;
